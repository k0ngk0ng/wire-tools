#!/usr/bin/env python3
"""Generate both package-manager definitions from locally verified release archives."""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
TARGETS=('darwin-arm64','linux-amd64','linux-arm64','windows-amd64')

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--version',required=True)
    parser.add_argument('--dist',type=Path,default=ROOT/'dist')
    parser.add_argument('--output',type=Path,default=ROOT/'packaging/generated')
    args=parser.parse_args()
    version=args.version.removeprefix('v')
    if not re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)',version):
        parser.error('package-manager releases require stable SemVer')
    output=args.output.resolve()
    if not output.is_relative_to(ROOT):
        parser.error('output must stay inside this checkout')
    entries={}
    for line in (args.dist/'SHA256SUMS').read_text().splitlines():
        digest,name=line.split()
        name=name.removeprefix('./')
        if not re.fullmatch(r'[0-9a-fA-F]{64}',digest) or name in entries or Path(name).name!=name:
            raise ValueError('invalid or duplicate checksum entry')
        entries[name]=digest.lower()
    values={}
    base='https://github.com/k0ngk0ng/wire-tools/releases/download/v'+version+'/'
    for target in TARGETS:
        name='wirectl-'+version+'-'+target+('.zip' if target.startswith('windows') else '.tar.gz')
        actual=hashlib.sha256((args.dist/name).read_bytes()).hexdigest()
        if entries.get(name)!=actual:
            raise ValueError('archive checksum mismatch: '+name)
        values[target]={'url':base+name,'hash':actual}
    mac=values['darwin-arm64']; arm=values['linux-arm64']; amd=values['linux-amd64']
    formula=f'''# Generated by scripts/manifests.py from verified release archives.
class Wirectl < Formula
  desc "Local APIs and CLI for encrypted connections, downloads and voice"
  homepage "https://github.com/k0ngk0ng/wire-tools"
  version "{version}"
  license all_of: ["MIT", "GPL-2.0-or-later", "LGPL-2.1-or-later"]

  on_macos do
    depends_on arch: :arm64
    url "{mac['url']}"
    sha256 "{mac['hash']}"
  end
  on_linux do
    on_arm do
      url "{arm['url']}"
      sha256 "{arm['hash']}"
    end
    on_intel do
      url "{amd['url']}"
      sha256 "{amd['hash']}"
    end
  end

  def install
    bin.install "bin/wirectl"
    libexec.install "libexec/wirectl-download" if File.directory?("libexec/wirectl-download")
    prefix.install "licenses", "LICENSE", "THIRD_PARTY_NOTICES.md", "wirectl-package.json"
    (bin/".wirectl-package-manager").write("homebrew\\n")
  end

  test do
    assert_equal version.to_s, shell_output("#{{bin}}/wirectl version").strip
    assert_match "download", shell_output("#{{bin}}/wirectl --help")
    assert_match "talk", shell_output("#{{bin}}/wirectl --help")
  end
end
'''
    win=values['windows-amd64']
    scoop={'version':version,'description':'Local APIs and CLI for encrypted connections, downloads and voice',
           'homepage':'https://github.com/k0ngk0ng/wire-tools','license':'MIT',
           'architecture':{'64bit':{'url':win['url'],'hash':win['hash']}},'bin':'bin/wirectl.exe',
           'post_install': '[System.IO.File]::WriteAllText("$dir\\bin\\.wirectl-package-manager", "scoop", [System.Text.Encoding]::ASCII)',
           'checkver':{'github':'https://github.com/k0ngk0ng/wire-tools'},
           'autoupdate':{'architecture':{'64bit':{'url':'https://github.com/k0ngk0ng/wire-tools/releases/download/v$version/wirectl-$version-windows-amd64.zip'}},
                         'hash':{'url':'$baseurl/SHA256SUMS','regex':'(?m)^([a-fA-F0-9]{64})\\s+\\*?(?:\\./)?$basename$'}}}
    (output/'Formula').mkdir(parents=True,exist_ok=True)
    (output/'bucket').mkdir(parents=True,exist_ok=True)
    (output/'Formula/wirectl.rb').write_text(formula)
    (output/'bucket/wirectl.json').write_text(json.dumps(scoop,indent=2)+'\n')
    # Flat names are convenient release assets for installations before catalog promotion.
    (output/'wirectl.rb').write_text(formula)
    (output/'wirectl.json').write_text(json.dumps(scoop,indent=2)+'\n')

if __name__=='__main__':
    try:
        main()
    except (ValueError,OSError) as error:
        raise SystemExit(str(error))
