// ConfigRequest creates a room and a local device configuration. Room secrets
// are generated by the service; joining an existing room uses PairRequest.
type ConfigRequest struct {
	Mode       string   `json:"mode,omitempty"`
	Listen     string   `json:"listen,omitempty"`
	Input      string   `json:"input,omitempty"`
	Output     string   `json:"output,omitempty"`
	RingOutput string   `json:"ring_output,omitempty"`
	Name       string   `json:"name,omitempty"`
	Peers      []string `json:"peers,omitempty"`
	Headphones bool     `json:"headphones,omitempty"`
}

type PairRequest struct {
	ConfigRequest
	Address string `json:"address"`
	Code    string `json:"code"`
}

// DeviceChange only changes local audio routing, preserving the saved room.
type DeviceChange struct {
	Input      *string `json:"input,omitempty"`
	Output     *string `json:"output,omitempty"`
	RingOutput *string `json:"ring_output,omitempty"`
}

type InvitationRequest struct {
	Room string `json:"room,omitempty"`
}
type Invitation struct {
	Address string    `json:"address"`
	Code    string    `json:"code"`
	Expires time.Time `json:"expires"`
}

type session struct {
	cancel context.CancelFunc
	done   chan struct{}
	err    error
}

// Manager lazily owns one audio session per state directory.
type Manager struct {
	ctx          context.Context
	cancel       context.CancelFunc
	dir, version string
	mu           sync.Mutex
	session      *session
	invitations  map[*pairing.Invitation]struct{}
	closed       bool
}

func New(ctx context.Context, dir, version string) *Manager {
	ctx, cancel := context.WithCancel(ctx)
	return &Manager{ctx: ctx, cancel: cancel, dir: dir, version: version, invitations: make(map[*pairing.Invitation]struct{})}
}

func (m *Manager) Ensure(ctx context.Context) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.closed {
		return errors.New("talk runtime is closed")
	}
	if _, err := control.RequestDirectBody(ctx, m.dir, "GET", "/status", nil); err == nil {
		return nil
	}
	if m.session != nil {
		select {
		case <-m.session.done:
			m.session = nil
		default:
		}
	}
	if m.session == nil {
		if _, err := config.Load(m.dir); err != nil {
			return err
		}
		sessionCtx, cancel := context.WithCancel(m.ctx)
		s := &session{cancel: cancel, done: make(chan struct{})}
		m.session = s
		go func() {
			s.err = command.Join(sessionCtx, m.dir, m.version)
			close(s.done)
		}()
	}
	s := m.session
	timer := time.NewTimer(15 * time.Second)
	defer timer.Stop()
	tick := time.NewTicker(40 * time.Millisecond)
	defer tick.Stop()
	for {
		if _, err := control.RequestDirectBody(ctx, m.dir, "GET", "/status", nil); err == nil {
			return nil
		}
		select {
		case <-ctx.Done():
			return ctx.Err()
		case <-m.ctx.Done():
			return m.ctx.Err()
		case <-s.done:
			m.session = nil
			if s.err != nil {
				return s.err
			}
			return errors.New("talk session ended during initialization")
		case <-timer.C:
			return errors.New("talk session initialization timed out")
		case <-tick.C:
		}
	}
}

func (m *Manager) stop(ctx context.Context) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.session == nil {
		return nil
	}
	s := m.session
	s.cancel()
	select {
	case <-s.done:
		m.session = nil
		return s.err
	case <-ctx.Done():
		return ctx.Err()
	}
}

func (m *Manager) Close() error {
	m.mu.Lock()
	m.closed = true
	m.cancel()
	for i := range m.invitations {
		_ = i.Close()
	}
	m.mu.Unlock()
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	return m.stop(ctx)
}

func respond(w http.ResponseWriter, code int, value any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(code)
	if value != nil {
		_ = json.NewEncoder(w).Encode(value)
	}
}
func fail(w http.ResponseWriter, code int, err error) {
	respond(w, code, map[string]string{"error": err.Error()})
}
func decode(w http.ResponseWriter, r *http.Request, value any) error {
	d := json.NewDecoder(http.MaxBytesReader(w, r.Body, 64<<10))
	d.DisallowUnknownFields()
	if err := d.Decode(value); err != nil {
		return err
	}
	var extra any
	if err := d.Decode(&extra); err != io.EOF {
		return errors.New("expected one JSON value")
	}
	return nil
}
func (c ConfigRequest) apply(current *config.Config) {
	if c.Listen != "" {
		current.Listen = c.Listen
	}
	current.Mode, current.Input, current.Output = c.Mode, c.Input, c.Output
	current.RingOutput = c.RingOutput
	current.Headphones, current.Name = c.Headphones, c.Name
	if c.Peers != nil {
		current.Peers = c.Peers
	}
}
func redacted(c config.Config) map[string]any {
	groups := make([]map[string]any, 0, len(c.RoomConfigs()))
	for _, g := range c.RoomConfigs() {
		groups = append(groups, map[string]any{"id": g.ID(), "name": g.Name, "mode": g.Mode, "listen": g.Listen, "peers": g.Peers, "listen_muted": g.Muted})
	}
	return map[string]any{"configured": true, "mode": c.Mode, "listen": c.Listen, "input": c.Input, "output": c.Output, "ring_output": c.RingOutput, "groups": groups, "active_group": c.CurrentID(), "output_gain_db": c.OutputGainDB}
}

func (m *Manager) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	switch r.URL.Path {
	case "/config":
		switch r.Method {
		case "GET":
			c, err := config.Load(m.dir)
			if errors.Is(err, os.ErrNotExist) {
				respond(w, 200, map[string]any{"configured": false})
				return
			}
			if err != nil {
				fail(w, 422, err)
				return
			}
			respond(w, 200, redacted(c))
		case "POST":
			var input ConfigRequest
			if err := decode(w, r, &input); err != nil {
				fail(w, 400, err)
				return
			}
			c, err := config.New()
			if err == nil {
				input.apply(&c)
				err = config.Save(m.dir, c)
			}
			if errors.Is(err, os.ErrExist) {
				fail(w, 409, errors.New("talk configuration already exists"))
				return
			}
			if err != nil {
				fail(w, 422, err)
				return
			}
			respond(w, 201, redacted(c))
		case "PATCH":
			var change DeviceChange
			if err := decode(w, r, &change); err != nil {
				fail(w, 400, err)
				return
			}
			if change.Input == nil && change.Output == nil && change.RingOutput == nil {
				fail(w, 400, errors.New("provide input, output or ring_output"))
				return
			}
			c, err := m.changeDevices(r.Context(), change)
			if err != nil {
				fail(w, 409, err)
				return
			}
			respond(w, 200, redacted(c))
		default:
			w.Header().Set("Allow", "GET, POST, PATCH")
			w.WriteHeader(405)
		}
	case "/session":
		switch r.Method {
		case "POST":
			if err := m.Ensure(r.Context()); err != nil {
				fail(w, 409, err)
				return
			}
			m.forward(w, r, "GET", "/status", nil)
		case "DELETE":
			ctx, cancel := context.WithTimeout(r.Context(), 5*time.Second)
			defer cancel()
			if err := m.stop(ctx); err != nil {
				fail(w, 503, err)
				return
			}
			w.WriteHeader(204)
		default:
			w.Header().Set("Allow", "POST, DELETE")
			w.WriteHeader(405)
		}
	case "/status":
		if r.Method != "GET" {
			w.Header().Set("Allow", "GET")
			w.WriteHeader(405)
			return
		}
		body, err := control.RequestDirectBody(r.Context(), m.dir, "GET", "/status", nil)
		if err == nil {
			w.Header().Set("Content-Type", "application/json")
			_, _ = w.Write(body)
			return
		}
		_, configErr := config.Load(m.dir)
		if configErr != nil && !errors.Is(configErr, os.ErrNotExist) {
			fail(w, 422, configErr)
			return
		}
		respond(w, 200, map[string]any{"active": false, "configured": configErr == nil, "version": m.version, "groups": []any{}})
	case "/devices":
		if r.Method != "GET" {
			w.Header().Set("Allow", "GET")
			w.WriteHeader(405)
			return
		}
		devices, err := audio.List()
		if err != nil {
			fail(w, 503, err)
			return
		}
		respond(w, 200, devices)
	case "/invitations":
		if r.Method != "POST" {
			w.Header().Set("Allow", "POST")
			w.WriteHeader(405)
			return
		}
		var input InvitationRequest
		if err := decode(w, r, &input); err != nil {
			fail(w, 400, err)
			return
		}
		invitation, err := m.invite(r.Context(), input)
		if err != nil {
			fail(w, 422, err)
			return
		}
		respond(w, 201, invitation)
	case "/pair":
		if r.Method != "POST" {
			w.Header().Set("Allow", "POST")
			w.WriteHeader(405)
			return
		}
		var input PairRequest
		if err := decode(w, r, &input); err != nil {
			fail(w, 400, err)
			return
		}
		c, err := m.pair(r.Context(), input)
		if errors.Is(err, os.ErrExist) {
			fail(w, 409, errors.New("talk configuration already exists"))
			return
		}
		if err != nil {
			fail(w, 422, err)
			return
		}
		respond(w, 201, redacted(c))
	case "/groups", "/call", "/media", "/mute", "/unmute", "/mute/output", "/unmute/output":
		allowed := "POST"
		if r.URL.Path == "/groups" {
			allowed = "GET, POST"
		}
		if r.Method != "POST" && !(r.URL.Path == "/groups" && r.Method == "GET") {
			w.Header().Set("Allow", allowed)
			w.WriteHeader(405)
			return
		}
		body, err := io.ReadAll(http.MaxBytesReader(w, r.Body, 1<<20))
		if err != nil {
			fail(w, 413, err)
			return
		}
		if r.URL.Path == "/groups" && r.Method == "POST" {
			var change config.GroupChange
			if json.Unmarshal(body, &change) == nil && change.Action == "mode" {
				var validated config.GroupChange
				d := json.NewDecoder(strings.NewReader(string(body)))
				d.DisallowUnknownFields()
				if err := d.Decode(&validated); err != nil {
					fail(w, 400, err)
					return
				}
				if err := m.changeMode(r.Context(), validated); err != nil {
					fail(w, 409, err)
					return
				}
				c, err := config.Load(m.dir)
				if err != nil {
					fail(w, 422, err)
					return
				}
				respond(w, 200, redacted(c))
				return
			}
		}
		if err := m.Ensure(r.Context()); err != nil {
			fail(w, 409, err)
			return
		}
		path := r.URL.Path
		if r.URL.RawQuery != "" {
			path += "?" + r.URL.RawQuery
		}
		m.forward(w, r, r.Method, path, body)
	default:
		http.NotFound(w, r)
	}
}

func (m *Manager) changeDevices(ctx context.Context, change DeviceChange) (config.Config, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	var c config.Config
	if m.closed {
		return c, errors.New("talk runtime is closed")
	}
	if _, err := control.RequestDirectBody(ctx, m.dir, "GET", "/status", nil); err == nil {
		return c, errors.New("disconnect the audio session with wirectl talk leave before changing devices")
	}
	unlock, err := control.Lock(m.dir)
	if err != nil {
		return c, err
	}
	defer unlock()
	c, err = config.Load(m.dir)
	if err != nil {
		return c, err
	}
	if change.Input != nil {
		c.Input = *change.Input
	}
	if change.Output != nil {
		c.Output = *change.Output
	}
	if change.RingOutput != nil {
		c.RingOutput = *change.RingOutput
	}
	return c, config.Rewrite(m.dir, c)
}

func (m *Manager) forward(w http.ResponseWriter, r *http.Request, method, path string, body []byte) {
	output, err := control.RequestDirectBody(r.Context(), m.dir, method, path, body)
	if err != nil {
		var response *control.HTTPError
		if errors.As(err, &response) {
			fail(w, response.StatusCode, err)
		} else {
			fail(w, 503, err)
		}
		return
	}
	if len(output) == 0 {
		w.WriteHeader(204)
		return
	}
	w.Header().Set("Content-Type", "application/json")
	_, _ = w.Write(output)
}

func (m *Manager) invite(ctx context.Context, input InvitationRequest) (Invitation, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.closed {
		return Invitation{}, errors.New("talk runtime is closed")
	}
	c, err := config.Load(m.dir)
	if errors.Is(err, os.ErrNotExist) {
		c, err = config.New()
		if err == nil {
			err = config.Save(m.dir, c)
		}
	}
	if err != nil {
		return Invitation{}, err
	}
	g, err := c.FindGroup(input.Room)
	if err != nil {
		return Invitation{}, err
	}
	// A session bound to port 0 has its actual UDP address in live status.
	if output, err := control.RequestDirectBody(ctx, m.dir, "GET", "/groups", nil); err == nil {
		var live struct {
			Groups []struct {
				RoomID string `json:"room_id"`
				Listen string `json:"listen"`
			} `json:"groups"`
		}
		if json.Unmarshal(output, &live) == nil {
			for _, room := range live.Groups {
				if room.RoomID == g.ID() {
					g.Listen = room.Listen
				}
			}
		}
	}
	_, port, err := net.SplitHostPort(g.Listen)
	if err != nil || port == "0" {
		return Invitation{}, errors.New("inviting requires a fixed listen port; start the session to allocate a port")
	}
	key, err := (config.Config{Key: g.Key}).KeyBytes()
	if err != nil {
		return Invitation{}, err
	}
	i, err := pairing.NewWithMode(g.Listen, key, g.Mode)
	if err != nil {
		return Invitation{}, err
	}
	m.invitations[i] = struct{}{}
	go func() {
		_ = i.Serve(m.ctx)
		m.mu.Lock()
		delete(m.invitations, i)
		m.mu.Unlock()
	}()
	return Invitation{Address: i.Address(), Code: i.Code, Expires: i.Expires}, nil
}

func (m *Manager) pair(ctx context.Context, input PairRequest) (config.Config, error) {
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.closed {
		return config.Config{}, errors.New("talk runtime is closed")
	}
	c, err := config.New()
	if err != nil {
		return c, err
	}
	input.ConfigRequest.apply(&c)
	// Resolve and validate the destination before consuming an invitation.
	remote, err := net.ResolveUDPAddr("udp", input.Address)
	if err != nil || remote.Port == 0 || len(remote.IP) == 0 || remote.IP.IsUnspecified() || remote.IP.IsMulticast() || remote.IP.Equal(net.IPv4bcast) {
		return c, errors.New("provide the inviter's reachable IP:port or hostname:port")
	}
	if err := c.ValidateGroups(); err != nil {
		return c, err
	}
	unlock, err := control.Lock(m.dir)
	if err != nil {
		return c, err
	}
	defer unlock()
	if _, err := config.Load(m.dir); err == nil {
		return c, os.ErrExist
	} else if !errors.Is(err, os.ErrNotExist) {
		return c, err
	}
	key, mode, err := pairing.ReceiveWithMode(ctx, remote.String(), strings.TrimSpace(input.Code))
	if err != nil {
		return c, fmt.Errorf("pairing failed: %w", err)
	}
	c.Key = base64.RawURLEncoding.EncodeToString(key)
	c.Mode = mode
	c.Peers = []string{input.Address}
	if err := config.Save(m.dir, c); err != nil {
		return c, fmt.Errorf("invitation consumed but saving the room failed: %w", err)
	}
	return c, nil
}

func (m *Manager) changeMode(ctx context.Context, change config.GroupChange) error {
	m.mu.Lock()
	defer m.mu.Unlock()
	if m.closed {
		return errors.New("talk runtime is closed")
	}
	if _, err := control.RequestDirectBody(ctx, m.dir, "GET", "/status", nil); err == nil {
		return errors.New("disconnect the audio session with wirectl talk leave before changing connection mode")
	}
	unlock, err := control.Lock(m.dir)
	if err != nil {
		return err
	}
	defer unlock()
	c, err := config.Load(m.dir)
	if err != nil {
		return err
	}
	next, err := c.Changed(change)
	if err != nil {
		return err
	}
	return config.Rewrite(m.dir, next)
}
